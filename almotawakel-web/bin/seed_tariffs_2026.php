$snap = static fn (): array => [
    'inv'   => (int) Database::scalar('SELECT COUNT(*) FROM permit_invoices'),
    'total' => (float) Database::scalar('SELECT COALESCE(SUM(total),0) FROM permit_invoices'),
];
