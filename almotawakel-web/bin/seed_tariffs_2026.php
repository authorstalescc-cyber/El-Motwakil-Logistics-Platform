    foreach (array_chunk($rows, 100) as $chunk) {
        $vals = []; $args = [];
        foreach ($chunk as $r) {
            $vals[] = '(?,?,?,?,?,?,?,?,1)';
            array_push($args, ...$r);
        }
        Database::exec(
            'INSERT INTO freight_tariffs
               (port_group, direction, service, zone_label, unit, price, effective_from, source_ref, active)
             VALUES ' . implode(',', $vals) . '
             ON DUPLICATE KEY UPDATE price = VALUES(price), source_ref = VALUES(source_ref), active = 1',
            $args
        );
    }
    foreach ($surcharges as [$port, $code, $label, $amount]) {
        Database::exec(
            'INSERT INTO freight_surcharges (port_group, code, label, amount, effective_from, active)
                  VALUES (?,?,?,?,?,1)
             ON DUPLICATE KEY UPDATE label = VALUES(label), amount = VALUES(amount), active = 1',
            [$port, $code, $label, $amount, $FROM]
        );
    }
    $pdo->commit();
} catch (\Throwable $e) {
    $pdo->rollBack();
    fwrite(STDERR, 'فشلت التعبئة: ' . $e->getMessage() . "\n");
    exit(1);
}

