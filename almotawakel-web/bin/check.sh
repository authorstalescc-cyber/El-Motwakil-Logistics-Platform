#!/usr/bin/env bash
# ═══════════════════════════════════════════════════════════════════════════
# فحص سريع للنظام كله — أمر واحد قبل أي رفع.
#
#   bash bin/check.sh
#
# ⚠️ **ليه السكربت ده موجود أصلاً؟** لأن تشغيل الفاحصات بحلقة عادية بيدّي نتيجة
#    **مضلِّلة**: ٤ فاحصات (`verify_installer` · `verify_restore` · `verify_v41` ·
#    `verify_v45`) بترفض الشغل على قاعدة العمل **عن قصد** وبتخرج بكود فشل، فبتتقري
#    «فاشلة» وهي سليمة. النتيجة إن كل جلسة كانت بتبدأ بإنذارات حمرا مش حقيقية،
#    والوقت بيروح في تحقيق «ده بتاعي ولا لأ؟» بدل الشغل.
#
# ⚠️ **`timeout` مش موجود على الماك** — أي حلقة بتستخدمه بتدّي فشلًا كاذبًا لكل
#    أمر (اتصادف فعليًا). عشان كده مش مستخدم هنا.
#
# ⚠️ **الشِل zsh ما بيقسّمش المتغيّر لكلمات** — عشان كده الشيبانج bash صراحةً
#    والمصفوفات مستخدمة بدل النصوص المفصولة بمسافات.
# ═══════════════════════════════════════════════════════════════════════════
set -uo pipefail
cd "$(dirname "$0")/.." || exit 1

LOGDIR="${TMPDIR:-/tmp}/almotawakel-check"
rm -rf "$LOGDIR"; mkdir -p "$LOGDIR"

# ⚠️ ANSI-C quoting `$'...'` إجبارية — bash **ما بيفسّرش** `\033` جوّه علامات
#    التنصيص العادية فبتتطبع حرفيًّا (مصيدة موثَّقة، وقعت تاني وأنا بكتب الملف ده).
R=$'\033[31m'; G=$'\033[32m'; Y=$'\033[33m'; D=$'\033[2m'; N=$'\033[0m'
# مؤشّر التقدّم للشاشة بس — في سجل أو أنبوب بيتحوّل لسطر واحد نضيف.
TTY=0; [ -t 1 ] && TTY=1

pass=0; failed=(); skipped=()
total=$(ls bin/verify_*.php | wc -l | tr -d ' ')
i=0

for f in bin/verify_*.php; do
  n=$(basename "$f" .php)
  i=$((i + 1))
  [ "$TTY" = 1 ] && printf '\r%s[%2d/%2d]%s %-42s' "$D" "$i" "$total" "$N" "$n"
  if php "$f" > "$LOGDIR/$n.log" 2>&1; then
    pass=$((pass + 1))
  elif grep -q 'قاعدة غير معزولة\|قاعدة اختبار معزولة' "$LOGDIR/$n.log"; then
    # حارس مقصود: الفاحص بيرفض قاعدة العمل — مش فشل.
    skipped+=("$n")
  else
    failed+=("$n")
  fi
done
[ "$TTY" = 1 ] && printf '\r%*s\r' 60 ''

echo "══════════════════════════════════════════════════════════"
printf "${G}ناجح: %d${N}   |   ${R}فاشل: %d${N}   |   ${Y}متخطّي بالتصميم: %d${N}   |   الإجمالي: %d\n" \
  "$pass" "${#failed[@]}" "${#skipped[@]}" "$total"

if [ ${#skipped[@]} -gt 0 ]; then
  printf "${Y}متخطّي${N} (محتاج قاعدة اختبار معزولة — مش فشل): %s\n" "${skipped[*]}"
fi

if [ ${#failed[@]} -gt 0 ]; then
  echo
  echo "الفاشلة — السطور المعلَّمة ✗:"
  for n in "${failed[@]}"; do
    printf "${R}  ✗ %s${N}\n" "$n"
    grep -E '✗' "$LOGDIR/$n.log" | head -3 | sed 's/^/      /'
    printf "${D}      السجل: %s/%s.log${N}\n" "$LOGDIR" "$n"
  done
  echo
  echo "⚠️ كود فشل فحصه ما يترفعش."
  exit 1
fi

echo
printf "${G}✓ النظام نضيف — جاهز للرفع.${N}\n"
