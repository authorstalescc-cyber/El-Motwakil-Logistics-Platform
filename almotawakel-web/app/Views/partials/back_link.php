<?php
/**
 * زر الرجوع الموحّد لشاشات المكتب — مقابل `m/_back.php` بتاع بوابة المندوب.
 *
 * ⚠️ **الحرف `‹` هو الصح في RTL** لأنه bidi-mirrored بيتقلب تلقائيًّا؛
 *    `←`/`→` مش بيتقلبوا فبيشاوروا في الاتجاه الغلط (المرحلة ٥). ولمّا الزرار
 *    مكتوب بالإيد في كل شاشة، أي تحسين (حجم لمس، وصولية، اتجاه) لازم يتكرر
 *    وواحد يتنسي — بالظبط اللي حصل في بوابة المندوب قبل ما تتجمّع في جزء واحد.
 *
 * `bin/verify_navigation.php` بيعدّ أزرار الرجوع المكتوبة بالإيد وبيمنع زيادتها.
 *
 * المتغيّرات:
 *   to     string   وجهة الرجوع (مسار نسبي — بيمرّ على `url()`)
 *   label  ?string  نص الزرار (الافتراضي «رجوع»)
 *   class  ?string  أصناف زيادة على `btn ghost`
 */
$__p_to    = (string) ($to ?? '');
$__p_label = (string) ($label ?? 'رجوع');
$__p_class = trim('btn ghost ' . (string) ($class ?? ''));
?>
<a class="<?= e($__p_class) ?>" href="<?= e(url($__p_to)) ?>"><span aria-hidden="true">‹</span> <?= e($__p_label) ?></a>
