<?php
/**
 * تنقّل بين أيام العرض — **عدسة قراءة، مش تغيير ليوم الشغل.**
 *
 * ⚠️ الفرق ده هو كل الفكرة: زرار «غيّر يوم العمل» بيحوّل النظام كله لوضع
 *    الكتابة على يوم تاني (وبيترفض لو اليوم متقفل)، أما ده فبيغيّر **اللي
 *    بتتفرّج عليه بس** ويفتح أي يوم مهما كان متقفل — القفل بيمنع الكتابة
 *    مش القراءة. من غير الفرق ده كان المالك بيعمل تسجيل خروج عشان يشوف
 *    يوم فات (بلاغ 2026-08-09).
 *
 * متغيّرات (من `RepCustodyController::dayNav`):
 *   day      string  اليوم المعروض
 *   workDay  string  يوم الشغل — اللي أي بند جديد هيتسجّل عليه
 *   prev     string  رابط اليوم اللي قبله
 *   next     string  رابط اللي بعده (فاضي = إحنا على النهاردة)
 *   work     string  رابط الرجوع ليوم الشغل (فاضي = إحنا عليه أصلاً)
 */
$day     = (string) ($day ?? '');
$workDay = (string) ($workDay ?? $day);
$prev    = (string) ($prev ?? '');
$next    = (string) ($next ?? '');
$work    = (string) ($work ?? '');
?>
<span class="day-nav">
  <?php /* ⚠️ **`chevron` هي الأيقونة الوحيدة الموجودة** (بتشاور شمال) — و`icon()`
           بترسم **دايرة فاضية بالسكوت** لأي اسم مش موجود، فـ`chevron-right`
           كانت هتعدّي بلا خطأ وتطلع فاضية. اتجاه «السابق» بيتعمل بقلب CSS
           (`.flip`) بدل ما نزوّد أيقونة تانية لنفس الرسمة. */ ?>
  <a class="day-nav-btn" href="<?= e($prev) ?>" title="اليوم اللي قبله"
     aria-label="اليوم اللي قبله"><span class="flip"><?= icon('chevron', 16) ?></span></a>
  <?php if ($next !== ''): ?>
    <a class="day-nav-btn" href="<?= e($next) ?>" title="اليوم اللي بعده"
       aria-label="اليوم اللي بعده"><?= icon('chevron', 16) ?></a>
  <?php else: ?>
    <span class="day-nav-btn off" aria-hidden="true"><?= icon('chevron', 16) ?></span>
  <?php endif; ?>
  <?php if ($work !== ''): ?>
    <?php /* ⚠️ **تحذير وظيفي** (قانون التصميم بند ١): مش شرح، ده تنبيه إن
             اللي بتقراه مش اليوم اللي هتكتب عليه — والزرار بيرجّعك. */ ?>
    <a class="day-nav-back" href="<?= e($work) ?>">
      <?= icon('alert', 14) ?> بتتفرّج بس — شغلك يوم <?= e(dfmt($workDay)) ?>
    </a>
  <?php endif; ?>
</span>
