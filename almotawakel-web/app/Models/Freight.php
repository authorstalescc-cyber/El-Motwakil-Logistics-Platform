<?php
namespace App\Models;

/**
 * ═══════════════════════════════════════════════════════════════════════════
 * وحدة التسعير — **السيارة** لا الحاوية (v96)
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * تصحيح المالك بالحرف: «ناولون العميل مش بيتحكم فيه عدد الحاويات ولكن عدد
 * السيارات — الكونتر ال٢٠ قدم السيارة تقدر تشيل اتنين فده ناولون واحد،
 * والكونتر ال٤٠ متقدرش العربية تشيل غيره فلو في حاويتين ٤٠ يبقى ٢ ناولون».
 *
 * ═══ القاعدة اتأكدت على بيانات النظام قبل ما تتكتب ═══
 *   • **٢٠ قدم:** ٢٧ بوليصة بحاويتين · ٥ بوليصة بحاوية (الفردة السايبة)
 *   • **٤٠ قدم:** ٤١ بوليصة، كلها حاوية واحدة — **بلا استثناء واحد**
 *   • **٤٠ مبرّد:** ٩ بوالص، كلها حاوية واحدة — بلا استثناء
 * والدليل القاطع إذن «اكما»: ٨ حاويات ٢٠ قدم = **٤ بوالص** (٤ سيارات)،
 * كل بوليصة ٢×٢٠ قدم بنولون ٢٥٬٠٠٠، والفاتورة ١١٠٬٠٠٠ ÷ ٤ = ٢٧٬٥٠٠ للسيارة.
 *
 * ⚠️ **دي المصدر الوحيد لتحويل «حاويات ← سيارات»** (قاعدة CLAUDE.md ②).
 *    الرقم ده بيظهر في فورم الفوترة وشاشة الإذن وبوابة `/m`، و**ممنوع** يتكتب
 *    `ceil($n / 2)` بالإيد في أي واحدة منهم — أول ما تتفرّق، الفاتورة تقول
 *    رقمًا والكارت يقول رقمًا تانيًا بلا أي خطأ ظاهر. `verify_v96` بيعدّ نقاط
 *    الاستدعاء ويفشل لو لقى قسمة يدوية على عدد حاويات.
 *
 * ⚠️ **التخمين بيموت أول ما البوالص تتسجّل.** اتأكد في كل صف من ١٤ فاتورة إن
 *    **البوليصة = سيارة** (عدد البوالص = عدد أرقام اللوحات دايمًا). فالدالة دي
 *    لازمة **قبل** إدخال البوالص بس؛ بعد كده العدد الحقيقي هو عدد البوالص،
 *    والشاشة بتقارن الاتنين وتنبّه لو اختلفوا.
 *
 * ⚠️ **بترجّع `null` لأي وصف مش حاوية معروفة** («دبابة» · «١٩ طرد») — نفس
 *    فلسفة `container_shape()`: ممنوع نخترع رقمًا لوصف مش عارفينه، لأن رقم
 *    غلط بيتقري كمعلومة صحيحة. الشاشة ساعتها ما بتعرضش عدد سيارات خالص.
 *
 * قراءة بحتة — بلا أي مساس بخزنة ولا تقفيل ولا عهدة، وبلا أي استعلام قاعدة.
 */
final class Freight
{
    /**
     * كام حاوية بتركب السيارة الواحدة، بمفتاح **مخرج `container_norm()`**.
     *
     * ⚠️ المفاتيح هنا لازم تفضل مطابقة لمخرجات `container_norm()` بالحرف
     *    (المصدر الوحيد لتوحيد التصنيف — v30). لو اتفرّقوا، الدالة بترجّع
     *    `null` لنوع معروف والشاشة تسكت من غير سبب واضح.
     *
     * ⚠️ **أوبن توب وفلات راك وتانك سعتهم ١ رغم إن `container_norm()` بيشيل
     *    مقاسهم.** الـ٢٠ منهم نظريًّا ممكن يتزاوج، بس مفيش ولا بوليصة واحدة في
     *    البيانات عملت كده، والافتراض المتحفّظ (سيارة لكل واحدة) بيغلط في اتجاه
     *    الزيادة اللي المالك بيشوفها قدامه ويصححها — مش في اتجاه نقص بيعدّي بالسكوت.
     */
    private const CAPACITY = [
        '20 قدم'    => 2,
        '20 مبرّد'  => 2,
        '40 قدم'    => 1,
        '40 مبرّد'  => 1,
        '45 قدم'    => 1,
        'أوبن توب'  => 1,
        'تانك'      => 1,
        'فلات راك'  => 1,
    ];

    /**
     * سعة السيارة لنوع حاوية — أو `null` لو النوع مش في الجدول.
     *
     * ⚠️ بتمرّ على `container_norm()` الأول عن قصد: النص الجاي من القاعدة ممكن
     *    يكون «1*40» أو «٢×٢٠ ث» بالأرقام العربية، والتوحيد مسؤولية دالة واحدة.
     */
    public static function capacity(?string $containerType): ?int
    {
        $norm = trim((string) container_norm($containerType ?? ''));
        if ($norm === '') { return null; }
        return self::CAPACITY[$norm] ?? null;
    }

    /**
     * عدد السيارات اللازمة لعدد حاويات من نوع واحد.
     *
     * ⚠️ **الفردة الزيادة بتركب لوحدها** — عشان كده `ceil` مش قسمة صحيحة:
     *    ٣ حاويات ٢٠ قدم = سيارتين (اتنين + واحدة)، مش سيارة ونص ولا سيارة.
     */
    public static function cars(?string $containerType, int $count): ?int
    {
        if ($count <= 0) { return null; }
        $cap = self::capacity($containerType);
        if ($cap === null || $cap < 1) { return null; }
        return (int) ceil($count / $cap);
    }

    /**
     * عدد السيارات من تفصيل الحاويات بتاع الإذن.
     *
     * نفس توقيع `Permit::containerLabel()` بالظبط عن قصد — الشاشة اللي بترسم
     * «٨×٢٠ قدم» هي نفسها اللي بتقول «٤ سيارات»، فمستحيل واحدة تتحدّث والتانية لأ.
     *
     * $breakdown: [['type' => '20 قدم', 'cnt' => 8], …] — الحمولة المختلطة
     * بتتجمّع **كل نوع لوحده** وبعدين تتجمع، لأن الـ٢٠ ما بيركبش مع الـ٤٠.
     *
     * ⚠️ **نوع واحد مجهول بيبطّل الإجابة كلها** (`null`). «٤ سيارات + نوع
     *    مش عارفينه» رقم ناقص بيتقري كرقم كامل — والصمت أنضف من رقم بينقص.
     */
    public static function carsFor(array $breakdown, int $fallbackCount = 0, ?string $fallbackType = null): ?int
    {
        $total = 0; $seen = false;
        foreach ($breakdown as $c) {
            $type = trim((string) ($c['type'] ?? ''));
            $cnt  = (int) ($c['cnt'] ?? 0);
            if ($type === '' || $cnt <= 0) { continue; }
            $cars = self::cars($type, $cnt);
            if ($cars === null) { return null; }
            $total += $cars; $seen = true;
        }
        if ($seen) { return $total; }
        // مفيش بوالص لسه ⇒ نقع على بيانات الإذن نفسه (التخمين قبل الإدخال)
        return self::cars($fallbackType, $fallbackCount);
    }

    /**
     * **بصمة الحمولة** — مفتاح التسعير لكل عميل (أساس محرّك العادات في v98).
     *
     * «٢×٢٠ قدم» و«١×٢٠ قدم» و«١×٤٠ قدم» **تلات أسعار منفصلة لنفس العميل**،
     * مش سعر واحد يتقسّم. الدليل: «بيردس» اتحاسب على حاوية واحدة مرتين بسعرين
     * مختلفين (١×٢٠ ← ١٤٬٠٠٠ · ١×٤٠ ← ١٧٬٥٠٠) — مش تغيّر سعر، دي حمولتين.
     */
    public static function loadSignature(?string $containerType, int $countPerCar): ?string
    {
        $norm = trim((string) container_norm($containerType ?? ''));
        if ($norm === '' || $countPerCar <= 0) { return null; }
        return $countPerCar . '×' . $norm;
    }

    /**
     * **النص الوحيد اللي أي شاشة بتعرضه عن السيارات** — الاشتقاق واليقين مع بعض.
     *
     * ⚠️ الدالة دي موجودة عشان **المنطق ما يتكتبش مرتين**. لو فورم الفوترة
     *    حسب «٥ (الواقع)» وكارت الإذن حسب «٤ (المشتق)»، الشاشتان بيقولوا رقمين
     *    لنفس الإذن ومحدّش هيعرف مين الصح — وده بالظبط اللي قاعدة «المصدر
     *    الوحيد» موجودة عشانه. `verify_v96` بيعدّ نقاط استدعائها.
     *
     * @param int $billCount عدد بوالص الإذن — **صفر معناه لسه ما اتسجّلتش**،
     *                       وساعتها بنعرض الاشتقاق موسومًا إنه متوقّع لا واقع.
     */
    public static function summary(array $breakdown, int $billCount, int $fallbackCount = 0, ?string $fallbackType = null): string
    {
        $derived = self::carsFor($breakdown, $fallbackCount, $fallbackType);
        if ($billCount > 0) {
            return self::label($billCount)
                . ($derived !== null && $derived !== $billCount ? ' — المتوقّع ' . intf($derived) : '');
        }
        return $derived !== null ? self::label($derived) . ' متوقّعة' : '';
    }

    /** «٤ سيارات» — نص جاهز للعرض، وسلسلة فاضية لو العدد مش معروف. */
    public static function label(?int $cars): string
    {
        if ($cars === null || $cars <= 0) { return ''; }
        if ($cars === 1) { return 'سيارة'; }
        if ($cars === 2) { return 'سيارتين'; }
        return intf($cars) . ($cars <= 10 ? ' سيارات' : ' سيارة');
    }
}
